"""Spot metadata loaded from data/locations.csv.

The slug is the stable identifier used for API file paths and URLs;
the display name is free to contain spaces/punctuation and to change.

resolved_cells caches, per Open-Meteo marine model source tag, the working
grid coordinate found for this spot (the seaward cell a dead-cell search
landed on). Persisting it lets subsequent runs batch every spot in one
multi-coordinate request instead of re-running the per-spot offset search.

closest_buoy preassigns the CDIP station whose comparison file the Buoys
view opens for this spot. Blank rows are filled once by buoys.build_buoys
(nearest active buoy) and persisted here, so it's never recomputed — and a
hand-edited value in the CSV always wins.

data/spot_orientation.csv (generated by build_spot_orientation.py from the
CDIP MOP shore normals and the Salix elevation grids) supplies each spot's
facing direction, offshore wind bearing and swell window, and
data/spot_bottom.csv (build_spot_bottom.py) its bottom type, from which
rating_config.size_range derives the working size range. Those are derived
rating metadata: any rating column filled in locations.csv overrides them.
"""
import csv
import json
import os
from dataclasses import dataclass, field

from rating_config import size_range

# Optional per-spot rating tuning. Any blank/absent column is derived from the
# spot's coastline orientation at rating time (see rating_config.build_profile),
# so these are refinements, not requirements — a new spot needs only lat/lon.
RATING_FIELDS = [
    'swell_min', 'swell_ideal', 'swell_max', 'offshore_dir',
    'size_min', 'size_ideal', 'size_max', 'tide_min', 'tide_max',
    'offshore_width',
]

ORIENTATION_FILE = 'spot_orientation.csv'      # next to locations.csv
BOTTOM_FILE = 'spot_bottom.csv'                 # next to locations.csv
# Columns of the orientation file that become derived rating metadata.
DERIVED_FIELDS = ['offshore_dir', 'swell_min', 'swell_ideal', 'swell_max']

# Hand override of the generated bottom type ('point' / 'reef' / 'beach'),
# for spots build_spot_bottom.py gets wrong (C Street reads as a beach).
BOTTOM_TYPES = ('point', 'reef', 'beach')

FIELDNAMES = [
    'site_name', 'slug', 'region', 'latitude', 'longitude', 'timezone',
    'closest_buoy', 'resolved_cells', *RATING_FIELDS, 'bottom_type',
]


def _opt_float(row, key):
    """Parse an optional numeric CSV cell; blank/missing/bad -> None."""
    raw = (row.get(key) or '').strip()
    if not raw:
        return None
    try:
        return float(raw)
    except ValueError:
        return None


@dataclass(frozen=True)
class Spot:
    name: str
    slug: str
    region: str
    latitude: float
    longitude: float
    timezone: str  # IANA name, e.g. "America/Los_Angeles"
    # CDIP station id ('' = unassigned; buoys.build_buoys fills it via
    # object.__setattr__ — the one sanctioned mutation of a frozen field).
    closest_buoy: str = ''
    # source tag -> [lat, lon] of the resolved working cell. frozen=True
    # protects the identity fields; the dict CONTENTS are mutated in place as
    # models resolve during a run (never reassign the attribute).
    resolved_cells: dict = field(default_factory=dict)
    # Hand-entered rating tuning: {RATING_FIELDS key: float}. Only keys the CSV
    # actually filled in are present; the rest are derived from coastline
    # orientation when the profile is built. Empty dict => fully derived.
    rating_meta: dict = field(default_factory=dict)
    # Generated orientation (spot_orientation.csv): facing bearing and the
    # DERIVED_FIELDS. Empty when the spot has no row in that file.
    facing: float = None
    derived_meta: dict = field(default_factory=dict)
    # Effective bottom type: the locations.csv override if set, else the
    # generated one (spot_bottom.csv); None => shared size range.
    bottom_type: str = None
    # The locations.csv override alone ('' when unset), kept for save_spots.
    bottom_override: str = ''

    @property
    def coast_normal(self):
        """Compass bearing (deg) this spot's coastline faces the open ocean.

        From spot_orientation.csv (MOP shore normal, ~+/-200 m of coast).
        Falls back to 270 (US West Coast breaks face broadly west) for a spot
        missing from that file, e.g. one added since it was last generated.
        """
        return 270.0 if self.facing is None else self.facing

    @property
    def profile_meta(self):
        """Rating metadata for build_profile: derived orientation, overridden
        by anything hand-entered in locations.csv."""
        return {**self.derived_meta, **self.rating_meta}


def _load_orientation(path):
    """slug -> (facing, {DERIVED_FIELDS key: float}); {} if no file."""
    try:
        f = open(path, newline='')
    except OSError:
        return {}
    with f:
        out = {}
        for row in csv.DictReader(f):
            out[row['slug']] = (
                _opt_float(row, 'facing'),
                {k: v for k in DERIVED_FIELDS
                 if (v := _opt_float(row, k)) is not None},
            )
        return out


def _load_bottom(path):
    """slug -> (bottom_type, slope, gravel_share); {} if no file."""
    try:
        f = open(path, newline='')
    except OSError:
        return {}
    with f:
        return {row['slug']: ((row.get('bottom_type') or '').strip() or None,
                              _opt_float(row, 'slope'), _opt_float(row, 'shore_gravel'))
                for row in csv.DictReader(f)}


def load_spots(path):
    spots = []
    orientation = _load_orientation(
        os.path.join(os.path.dirname(path), ORIENTATION_FILE))
    bottom = _load_bottom(os.path.join(os.path.dirname(path), BOTTOM_FILE))
    with open(path, newline='') as f:
        for row in csv.DictReader(f):
            # Tolerate the column being absent (old CSV), blank, or malformed.
            resolved = {}
            raw = (row.get('resolved_cells') or '').strip()
            if raw:
                try:
                    resolved = json.loads(raw)
                except Exception:
                    resolved = {}
            rating_meta = {k: v for k in RATING_FIELDS
                           if (v := _opt_float(row, k)) is not None}
            facing, derived = orientation.get(row['slug'].strip(), (None, {}))
            override = (row.get('bottom_type') or '').strip().lower()
            override = override if override in BOTTOM_TYPES else ''
            kind, slope, gravel = bottom.get(row['slug'].strip(), (None, None, None))
            kind = override or kind
            lo, ideal, hi = size_range(kind, slope, gravel)
            sizes = {'size_min': lo, 'size_ideal': ideal, 'size_max': hi}
            spots.append(Spot(
                name=row['site_name'].strip(),
                slug=row['slug'].strip(),
                region=row['region'].strip(),
                latitude=float(row['latitude']),
                longitude=float(row['longitude']),
                timezone=row['timezone'].strip(),
                closest_buoy=(row.get('closest_buoy') or '').strip(),
                resolved_cells=resolved,
                rating_meta=rating_meta,
                facing=facing,
                derived_meta={**derived, **sizes},
                bottom_type=kind,
                bottom_override=override,
            ))
    return spots


def save_spots(path, spots):
    """Write spots back to CSV, preserving original columns and appending the
    resolved_cells JSON blob (compact, or empty string when unresolved)."""
    with open(path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
        writer.writeheader()
        for spot in spots:
            blob = ''
            if spot.resolved_cells:
                blob = json.dumps(spot.resolved_cells, separators=(',', ':'))
            row = {
                'site_name': spot.name,
                'slug': spot.slug,
                'region': spot.region,
                'latitude': spot.latitude,
                'longitude': spot.longitude,
                'timezone': spot.timezone,
                'closest_buoy': spot.closest_buoy,
                'resolved_cells': blob,
            }
            # Only write back rating cells the CSV actually supplied, so derived
            # spots stay blank (and keep deriving) rather than being frozen.
            for k in RATING_FIELDS:
                row[k] = spot.rating_meta.get(k, '')
            row['bottom_type'] = spot.bottom_override
            writer.writerow(row)
